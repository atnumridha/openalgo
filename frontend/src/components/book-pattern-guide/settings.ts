/** Reject invalid settings through explicit bounded normalization; never propagate NaN into plans. */
export function resolveBookSettings(input: Partial<BookSettings> = {}): BookSettings {
  const s = {
    ...DEFAULT_BOOK_SETTINGS,
    ...input,
    disabledPatterns: [...(input.disabledPatterns ?? [])],
  }
  for (const key of Object.keys(DEFAULT_BOOK_SETTINGS) as (keyof BookSettings)[]) {
    if (
      typeof DEFAULT_BOOK_SETTINGS[key] === 'number' &&
      (!Number.isFinite(s[key]) || (s[key] as number) < 0)
    )
      (s as unknown as Record<string, unknown>)[key] = DEFAULT_BOOK_SETTINGS[key]
  }
  s.pivotLeft = Math.max(2, Math.min(10, Math.floor(s.pivotLeft)))
  s.pivotRight = Math.max(2, Math.min(10, Math.floor(s.pivotRight)))
  for (const k of [
    'atrPeriod',
    'pivotSpacing',
    'shapeMinBars',
    'shapeMaxBars',
    'poleMinBars',
    'poleMaxBars',
    'flagMinBars',
    'flagMaxBars',
    'cupMinBars',
    'cupMaxBars',
    'handleMinBars',
    'handleMaxBars',
    'averageBodyPeriod',
    'candleTriggerBars',
    'retestBars',
    'failedBreakoutBars',
    'levelLookback',
    'multiSwingMinBars',
    'multiSwingMaxBars',
    'maFast',
    'maSlow',
    'maSlopeBars',
    'trendWarmup',
    'rsiPeriod',
    'macdFast',
    'macdSlow',
    'macdSignal',
    'volumePeriod',
    'divergenceMinBars',
    'divergenceMaxBars',
    'planExpiryBars',
    'labelLookback',
    'maxDrawings',
    'maxPolylines',
    'maxLabels',
    'maxLines',
  ] as const)
    s[k] = Math.max(1, Math.floor(s[k]))
  if (s.gapPolicy !== 'explicit' && s.gapPolicy !== 'continuous') s.gapPolicy = 'explicit'
  if (s.maType !== 'ema' && s.maType !== 'sma') s.maType = 'ema'
  return s
}
